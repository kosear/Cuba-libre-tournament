export const LANGS = ['en', 'id', 'ru'];
let current = (() => {
  try { const l = localStorage.getItem('lang'); return LANGS.includes(l) ? l : 'en'; } catch { return 'en'; }
})();

export const lang = () => current;
export function setLang(l) {
  current = LANGS.includes(l) ? l : 'en';
  try { localStorage.setItem('lang', current); } catch {}
  document.documentElement.lang = current;
}

export function t(key, params = {}) {
  const s = DICT[current][key] ?? DICT.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? ''));
}

